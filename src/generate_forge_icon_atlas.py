#!/usr/bin/env python3
"""Bake 12 forge & oath icons into a C++ runtime atlas.

Separate from SKILL_ICONS_AI — these are NEW icons for the Soul Forge shop,
not the skill icons. 64x64 indexed 128-color palette.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
DESIGN = ROOT.parent / 'design'
OUT = ROOT / 'forge_icon_atlas.h'
SIZE = 128
COLORS = 128

# Frame background colour (non-evolved) used to composite transparent pixels
FRAME_BG = (0x18, 0x12, 0x28)

ASSETS = [
    (0,   DESIGN / 'forge_blade_strength_v2.png'),    # Сила клинка
    (1,   DESIGN / 'forge_titan_blood_v2.png'),       # Кровь титана
    (2,   DESIGN / 'forge_wind_wings_v2.png'),        # Крылья ветра
    (3,   DESIGN / 'forge_magnet_v2.png'),            # Древний магнит
    (4,   DESIGN / 'forge_blessing_v2.png'),          # Благословение
    (5,   DESIGN / 'forge_armor_v2.png'),             # Кованая броня
    (6,   DESIGN / 'oath_blood_v2.png'),              # Кровавый договор
    (7,   DESIGN / 'oath_hunter_mark_v2.png'),        # Охотничий знак
    (8,   DESIGN / 'oath_black_arsenal_v2.png'),      # Чёрный арсенал
    (9,   DESIGN / 'oath_hungry_pack_v2.png'),        # Марш голодной стаи
    (10,  DESIGN / 'oath_loot_sign_v2.png'),         # Знак добытчика
    (11,  DESIGN / 'oath_ash_pack_v2.png'),          # Пепельная свора
]

import numpy as np

def fmt_array(values, per_line=24, formatter=str):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append('    ' + ', '.join(formatter(v) for v in values[i:i+per_line]) + ',')
    return '\n'.join(lines)

lines = [
    '#pragma once',
    '#include <stdint.h>',
    '',
    '// Generated by generate_forge_icon_atlas.py; 128x128 indexed assets for Soul Forge shop.',
    '',
]

for wid, path in ASSETS:
    img = Image.open(path).convert('RGBA').resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    arr = np.array(img).astype(np.float32)
    rgb = arr[:, :, :3]
    alpha = arr[:, :, 3:4] / 255.0
    rgb = rgb * alpha + np.array(FRAME_BG, dtype=np.float32) * (1.0 - alpha)
    image = Image.fromarray(rgb.astype(np.uint8), 'RGB')
    q = image.quantize(colors=COLORS, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.FLOYDSTEINBERG)
    indices = list(q.getdata())
    raw_palette = q.getpalette()[:COLORS * 3]
    palette = []
    for i in range(COLORS):
        r, g, b = raw_palette[i * 3:i * 3 + 3]
        palette.append(0xFF000000 | (r << 16) | (g << 8) | b)
    name = f'FORGE_ICON_{wid:02d}'
    lines.extend([
        f'static const uint32_t {name}_PALETTE[{COLORS}] = {{',
        fmt_array(palette, 8, lambda v: f'0x{v:08X}u'),
        '};',
        f'static const uint8_t {name}_PIXELS[{SIZE * SIZE}] = {{',
        fmt_array(indices, 24, lambda v: str(int(v))),
        '};',
        '',
    ])

lines.extend([
    'static const BakedIconImage FORGE_ICONS[12] = {',
])
for wid, _ in ASSETS:
    name = f'FORGE_ICON_{wid:02d}'
    lines.append(f'    {{{SIZE},{SIZE},{name}_PALETTE,{name}_PIXELS}},')
lines.extend([
    '};',
    '',
])
OUT.write_text('\n'.join(lines), encoding='utf-8')
total_indices = len(ASSETS) * SIZE * SIZE
total_palette = len(ASSETS) * COLORS * 4
print(f'Wrote {OUT} ({OUT.stat().st_size:,} bytes; {total_indices:,} runtime palette indices + {total_palette:,} palette bytes).')
