def fmt_array(values, per_line=24, formatter=str):
    lines=[]
    for i in range(0,len(values),per_line):
        lines.append('    ' + ', '.join(formatter(v) for v in values[i:i+per_line]) + ',')
    return '\n'.join(lines)

lines = [
    '#pragma once',
    '#include <stdint.h>',
    '',
    '// Generated by generate_skill_icon_atlas.py; 64x64 indexed assets, no runtime PNG dependency.',
    'struct BakedIconImage { int width, height; const uint32_t* palette; const uint8_t* pixels; };',
    '',
]
# Frame background colour (non-evolved) used to composite transparent pixels
# so they blend seamlessly into the skill-icon button in-game.
FRAME_BG = (0x18, 0x12, 0x28)

for wid, path in ASSETS:
    img = Image.open(path).convert('RGBA').resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    arr = np.array(img).astype(np.float32)
    rgb = arr[:, :, :3]
    alpha = arr[:, :, 3:4] / 255.0
    # Composite RGBA onto FRAME_BG so transparent areas become the button bg colour.
    rgb = rgb * alpha + np.array(FRAME_BG, dtype=np.float32) * (1.0 - alpha)
    image = Image.fromarray(rgb.astype(np.uint8), 'RGB')
    q = image.quantize(colors=COLORS, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.FLOYDSTEINBERG)
    indices=list(q.getdata())
    raw_palette=q.getpalette()[:COLORS*3]
    palette=[]
    for i in range(COLORS):
        r,g,b=raw_palette[i*3:i*3+3]
        palette.append(0xFF000000 | (r<<16) | (g<<8) | b)
    name = f'SKILL_ICON_{wid:02d}_AI'
    lines.extend([
        f'static const uint32_t {name}_PALETTE[{COLORS}] = {{',
        fmt_array(palette,8,lambda v:f'0x{v:08X}u'),
        '};',
        f'static const uint8_t {name}_PIXELS[{SIZE*SIZE}] = {{',
        fmt_array(indices,24,lambda v:str(int(v))),
        '};',
        '',
    ])
lines.extend([
    'static const BakedIconImage SKILL_ICONS_AI[40] = {',
])
for wid, _ in ASSETS:
    name = f'SKILL_ICON_{wid:02d}_AI'
    lines.append(f'    {{{SIZE},{SIZE},{name}_PALETTE,{name}_PIXELS}},')
lines.extend([
    '};',
    '',
])
OUT.write_text('\n'.join(lines),encoding='utf-8')
total_indices = len(ASSETS) * SIZE * SIZE
total_palette = len(ASSETS) * COLORS * 4
print(f'Wrote {OUT} ({OUT.stat().st_size:,} bytes; {total_indices:,} runtime palette indices + {total_palette:,} palette bytes).')
