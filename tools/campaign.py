# Развилки по порядку актов: (акт, верхняя голова, нижняя голова).
# Это те же четыре пары, что стоят в src/game.h (CAMPAIGN_FORKS), и check()
# сверяет, что обе головы растут из одного узла и ведут в один акт.
FORKS = [(2, 4, 14), (3, 8, 18), (4, 11, 21), (5, 27, 28)]

# Короткие имена для карты кампании. Полные названия доходят до 255 px и в
# узкой колонке змейки обрезаются посреди слова, поэтому у четырёх дел есть
# отдельное имя. Поле mapTitle в src/game.h заполняется только отсюда.
MAP_TITLES = {
    5: "СЕСТРА НЕ СЛЫШИТ",
    12: "ПИСАРЬ СТЁР СЕБЯ",
    18: "ПУСТЫЕ СТРАНИЦЫ",
    24: "РЕЗЕРВНЫЙ ПРИКАЗ",
}

# Следы: 0 — общее дело, 1 — «СВИДЕТЕЛЬ», 2 — «КОПИЯ».
TRACKS = {0: ("ОБЩЕЕ", "общее для обоих следов"),
          1: ("СВИДЕТЕЛЬ", "идти по живым: показания, списки, реестр"),
          2: ("КОПИЯ", "идти по машинам: колбы, слепки, двойники")}

MISSIONS = []
for order, (src, act, track, prereq, kind, seals, reinforced) in enumerate(_LAYOUT):
    base = dict(_LEGACY[src])
    base.update(act=act, track=track, prereq=list(prereq), kind=kind,
                seals=seals, reinforced=reinforced, brief=src,
                case="%03d" % (order + 1))
    if track:
        base["subtitle"] = "СЛЕД %s • %s" % ("А" if track == 1 else "Б", TRACKS[track][0])
    MISSIONS.append(base)

ACTS = {
    1: ("ПЕПЕЛ НА СТОЛЕ", "Первые дела: участок у ворот, свидетель без имени, три удара колокола."),
    2: ("ГОЛОС В КОЛБЕ", "Крипта, колбы и копия, которая отвечает правильно и не понимает вопросов."),
    3: ("РЕЕСТР", "Затопленные книги, имена на камне и человек, который стёр себя первым."),
    4: ("АРХИВ", "Кабинет Архивариуса, копия Свидетеля и выбор: память или право на утрату."),
    5: ("СЕРДЦЕ АРХИВА", "Резервная копия приказа, три эхо и последняя ночь."),
}


def cpp_rows():
    out = []
    for i, m in enumerate(MISSIONS):
        pre = (list(m["prereq"]) + [-1, -1])[:2]
        short = ', "{map}"}},'.format(map=MAP_TITLES[i]) if i in MAP_TITLES else "},"
        out.append(
            '    {{"{title}", "{subtitle}", "{briefing}", "{objective}", "{boss}", '
            "{duration}, {bossTime}, {bossType}, {act}, 0x{seals:02X}u, {trio}, "
            "{act2}, {kind}, {preA}, {preB}, {rein}, {track}, {brief}".format(
                title=m["title"], subtitle=m["subtitle"],
                briefing=m["briefing"].replace('"', '\\"'),
                objective=m["objective"], boss=m["boss"],
                duration=m["duration"], bossTime=m["bossTime"], bossType=m["bossType"],
                act=m["act"], seals=m["seals"], trio="true" if m["kind"] == 1 else "false",
                act2=m["act"], kind=m["kind"], preA=pre[0], preB=pre[1],
                rein="true" if m.get("reinforced") else "false",
                track=m.get("track", 0), brief=m.get("brief", -1)) + short)
    return "\n".join(out)


def md_act(act):
    lines = [f"### Акт {act}. {ACTS[act][0]}", "", ACTS[act][1], "",
             "| # | Дело | Миссия | Цель | Босс | Длительность |", "|---|------|--------|------|------|--------------|"]
    for i, m in enumerate(MISSIONS):
        if m["act"] != act:
            continue
        lines.append("| {n} | {case} | {title} — {subtitle} | {objective} | {boss} | {mins} мин |".format(
            n=i + 1, case=m["case"], title=m["title"], subtitle=m["subtitle"],
            objective=m["objective"], boss=m["boss"],
            mins=round((m["duration"] + m["bossTime"]) / 60, 1)))
    return "\n".join(lines)


def check():
    problems = 0
    for i, m in enumerate(MISSIONS):
        for p in m["prereq"]:
            # Ссылка «вперёд» по номеру допустима: головы акта III открываются
            # с ЛЮБОЙ полосы акта II, а нижняя полоса лежит в таблице ниже.
            # Недопустимо только открывать дело делом из будущего акта.
            if MISSIONS[p]["act"] > m["act"]:
                print(f"! миссия {i + 1} (акт {m['act']}) ждёт миссию {p + 1} "
                      f"из акта {MISSIONS[p]['act']}")
                problems += 1
    # В актах с развилкой дел вдвое больше, но лежат они в двух колонках-следах,
    # поэтому в одной колонке не должно быть больше CAMPAIGN_ACT_MAX_ROWS строк.
    for act in range(1, 6):
        rows = {}
        for m in MISSIONS:
            if m["act"] == act:
                t = m.get("track", 0)
                rows[t] = rows.get(t, 0) + 1
        if not rows:
            print(f"! акт {act} пуст")
            problems += 1
        for track, n in sorted(rows.items()):
            if n > 6:
                print(f"! акт {act}, след {track}: {n} дел — в колонке помещается 6")
                problems += 1
    # Развилки: головы одной развилки должны висеть на одном родителе и вести в
    # один акт — иначе выбор перестаёт быть выбором, а становится ступенькой.
    merge = next(i for i, m in enumerate(MISSIONS) if m["act"] == 5)
    for act, headA, headB in FORKS:
        a, b = MISSIONS[headA], MISSIONS[headB]
        if a["act"] != act or b["act"] != act:
            print(f"! развилка акта {act}: головы стоят в разных актах")
            problems += 1
        if sorted(a["prereq"]) != sorted(b["prereq"]):
            print(f"! развилка акта {act}: головы {headA + 1} и {headB + 1} "
                  f"растут из разных узлов")
            problems += 1
        # Обе головы обязаны открываться после любого прохождения прошлого акта.
        if act > 2:
            # Акт V — исключение: развилка стоит на стволе после слияния полос.
            if act == 5:
                if not a["prereq"] or a["prereq"][0] <= merge:
                    print("! финальная развилка не связана со стволом акта V")
                    problems += 1
            else:
                prev_ends = [i for i, m in enumerate(MISSIONS)
                             if m["act"] == act - 1 and m.get("track") in (1, 2)]
                last_a = max(i for i in prev_ends if MISSIONS[i].get("track") == 1)
                last_b = max(i for i in prev_ends if MISSIONS[i].get("track") == 2)
                if not (last_a in a["prereq"] and last_b in b["prereq"]):
                    print(f"! развилка акта {act}: головы не открываются с обеих полос")
                    problems += 1
    # У каждого следа должен быть путь до финала, иначе выбор ветки снова тупик.
    for track in (1, 2):
        last = [i for i, m in enumerate(MISSIONS)
                if m.get("track") == track and m["act"] == 4]
        if not last:
            print(f"! след {track} не доходит до конца акта IV")
            problems += 1
        elif max(last) not in MISSIONS[merge]["prereq"]:
            print(f"! акт V не открывается следом {track}")
            problems += 1
        runs = (sum(1 for m in MISSIONS if m["act"] == 1) +
                sum(1 for m in MISSIONS if m.get("track") == track) +
                sum(1 for m in MISSIONS if m["act"] == 5) -
                1)   # одна из двух голов финальной развилки не играется
        print(f"  прохождение по следу {track}: {runs} дел")
    # Каждый прежний текст должен найти себе место: иначе пропадёт записанный голос.
    for old in range(len(_LEGACY)):
        places = [i for i, m in enumerate(MISSIONS) if m["brief"] == old]
        if not places:
            print(f"! текст {old:02d} «{_LEGACY[old]['title']}» никуда не попал")
            problems += 1
    if len(MISSIONS) > 32:
        print(f"! {len(MISSIONS)} дел не влезают в 32-битную маску сейва")
        problems += 1
    print(f"миссий: {len(MISSIONS)}")
    for act in range(1, 6):
        print(f"  акт {act}: {sum(1 for m in MISSIONS if m['act'] == act)}")
    return problems


if __name__ == "__main__":
    import sys
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "cpp":
        print(cpp_rows())
    elif cmd == "md":
        for act in range(1, 6):
            print(md_act(act))
            print()
    else:
        sys.exit(1 if check() else 0)
